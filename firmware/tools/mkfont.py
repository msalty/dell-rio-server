"""Render the receiver's fonts into a C header.

The Rio's vacuum fluorescent display is 128x64 with four brightness levels,
so glyphs are stored anti-aliased at 2 bits per pixel. Fonts are rendered
from DejaVu Sans (Bitstream Vera licence) covering Latin-1.

    python3 tools/mkfont.py > src/fonts.h
"""

from __future__ import annotations

import sys

from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"
FONTS = [
    # name, file, pixel size, line height, baseline offset tweak
    ("small", "DejaVuSans.ttf", 9, 10),
    ("medium", "DejaVuSans.ttf", 11, 13),
    ("bold", "DejaVuSans-Bold.ttf", 11, 13),
    ("large", "DejaVuSans-Bold.ttf", 15, 17),
]
FIRST, LAST = 32, 255


def shade(v: int) -> int:
    # Bias toward full brightness so small text stays crisp on the VFD.
    if v >= 150:
        return 3
    if v >= 90:
        return 2
    if v >= 40:
        return 1
    return 0


def render(file: str, size: int, line: int):
    font = ImageFont.truetype(DEJAVU + file, size)
    ascent, descent = font.getmetrics()
    top = (line - (ascent + descent)) // 2
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if 127 <= code < 160:
            ch = "?"
        adv = max(1, int(round(font.getlength(ch))))
        if code == 32:
            adv = max(2, size // 3)
        img = Image.new("L", (adv + 4, line), 0)
        ImageDraw.Draw(img).text((0, top), ch, font=font, fill=255)
        bbox = img.getbbox()
        width = adv
        if bbox and bbox[2] > adv:
            width = bbox[2]
        px = [[shade(img.getpixel((x, y))) for x in range(width)] for y in range(line)]
        glyphs.append((adv, width, px))
    return glyphs


def main() -> None:
    out = sys.stdout
    out.write("/* Generated by tools/mkfont.py from DejaVu Sans. Do not edit. */\n")
    out.write("/* DejaVu fonts: Bitstream Vera licence (see firmware/LICENSE.fonts). */\n")
    out.write("#ifndef FONTS_H\n#define FONTS_H\n#include \"gfx.h\"\n\n")
    for name, file, size, line in FONTS:
        glyphs = render(file, size, line)
        data = bytearray()
        table = []
        for adv, width, px in glyphs:
            stride = (width + 3) // 4
            table.append((adv, width, len(data)))
            for row in px:
                packed = bytearray(stride)
                for x, v in enumerate(row):
                    packed[x // 4] |= v << ((x % 4) * 2)
                data += packed
        out.write(f"static const unsigned char font_{name}_data[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            out.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        out.write("};\n")
        out.write(f"static const struct glyph font_{name}_glyphs[{len(table)}] = {{\n")
        for i in range(0, len(table), 6):
            out.write("  " + " ".join(f"{{{a},{w},{o}}}," for a, w, o in table[i:i + 6]) + "\n")
        out.write("};\n")
        out.write(f"const struct font font_{name} = {{ {line}, {FIRST}, {LAST}, "
                  f"font_{name}_glyphs, font_{name}_data }};\n\n")
    out.write("#endif\n")


if __name__ == "__main__":
    main()
