"""Render the RioServer NG logo.

Writes two things, both committed so that the firmware build needs no PIL:

  src/logo.h              the logo at 4 brightness levels (128x40, 2 bits per
                          pixel) for the firmware's own boot screen
  art/splash<N>.pbm       1-bit 128x64 splash screens that replace the
                          kernel's built-in "DELL"/"Rio" screens
                          (see tools/kernel_splash.py)

    python3 tools/mklogo.py

The logo is a slanted "Rio" cut by speed stripes, with an "NG" badge, drawn
from DejaVu Sans Bold (Bitstream Vera licence).
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEJAVU = "/usr/share/fonts/truetype/dejavu/"
W, H, LOGO_H = 128, 64, 40
SS = 8  # supersampling factor

# Kernel splash screens, by the index the kernel uses: 0 is drawn by the
# receiver's boot loader, 1 while the kernel can't find a server and 2 once
# the kernel starts (followed directly by the firmware's own boot screen,
# which draws the same logo in the same place).
SPLASH = [
    ("Searching for server", None),
    ("Music server not found", None),
    ("Starting...", None),
]


def logo_image() -> Image.Image:
    """The logo as an 8-bit greyscale image, W x LOGO_H."""
    big = Image.new("L", (W * SS, LOGO_H * SS), 0)
    d = ImageDraw.Draw(big)
    rio = ImageFont.truetype(DEJAVU + "DejaVuSans-Bold.ttf", 44 * SS)
    ng = ImageFont.truetype(DEJAVU + "DejaVuSans-Bold.ttf", 13 * SS)
    rio_w = d.textlength("Rio", font=rio)
    badge_w = d.textlength("NG", font=ng) + 5 * SS
    gap = 2 * SS
    x0 = (W * SS - (rio_w + gap + badge_w)) / 2 + SS
    d.text((x0, -6 * SS), "Rio", font=rio, fill=255)
    bx, by = x0 + rio_w + gap, 7 * SS
    d.rounded_rectangle((bx, by, bx + badge_w, by + 15 * SS), radius=4 * SS, fill=255)
    d.text((bx + 2.5 * SS, by - 0.5 * SS), "NG", font=ng, fill=0)
    # speed stripes, widening toward the bottom
    for y, h in ((26, 1), (30, 1), (33, 2)):
        d.rectangle((0, y * SS, W * SS, (y + h) * SS - 1), fill=0)
    k = 0.24  # italic slant
    big = big.transform(big.size, Image.AFFINE, (1, k, -k * big.size[1] * 0.5, 0, 1, 0),
                        resample=Image.BICUBIC)
    return big.resize((W, LOGO_H), Image.LANCZOS)


def level(v: int) -> int:
    # same thresholds as the fonts (tools/mkfont.py)
    return 3 if v >= 150 else 2 if v >= 90 else 1 if v >= 40 else 0


def write_header(logo: Image.Image) -> None:
    stride = W // 4
    data = bytearray(stride * LOGO_H)
    for y in range(LOGO_H):
        for x in range(W):
            data[y * stride + x // 4] |= level(logo.getpixel((x, y))) << ((x % 4) * 2)
    lines = [
        "/* Generated by tools/mklogo.py. Do not edit. */",
        "#ifndef LOGO_H_INCLUDED",
        "#define LOGO_H_INCLUDED",
        f"#define LOGO_W {W}",
        f"#define LOGO_H {LOGO_H}",
        "/* rows of LOGO_W/4 bytes, 2 bits per pixel, leftmost pixel in the low bits */",
        f"static const unsigned char logo_data[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 32):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 32]) + ",")
    lines += ["};", "#endif", ""]
    (ROOT / "src" / "logo.h").write_text("\n".join(lines))


def splash(logo: Image.Image, line1: str, line2: str | None) -> Image.Image:
    im = Image.new("1", (W, H), 0)
    im.paste(logo.point(lambda v: 255 if v > 120 else 0).convert("1"), (0, 0))
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    f1 = ImageFont.truetype(DEJAVU + "DejaVuSans.ttf", 11)
    y = 44 if line2 is None else 41
    d.text(((W - d.textlength(line1, font=f1)) / 2, y), line1, font=f1, fill=1)
    if line2:
        f2 = ImageFont.truetype(DEJAVU + "DejaVuSans.ttf", 9)
        d.text(((W - d.textlength(line2, font=f2)) / 2, 54), line2, font=f2, fill=1)
    return im


def main() -> None:
    logo = logo_image()
    write_header(logo)
    art = ROOT / "art"
    art.mkdir(exist_ok=True)
    for i, (line1, line2) in enumerate(SPLASH):
        # PBM is exactly the kernel's format: 1 bit per pixel, MSB = leftmost
        splash(logo, line1, line2).save(art / f"splash{i}.pbm")
    print(f"wrote src/logo.h and {len(SPLASH)} splash screens in art/")


if __name__ == "__main__":
    main()
